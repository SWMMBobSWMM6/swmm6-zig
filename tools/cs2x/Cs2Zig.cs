// Cs2Zig - translate the generated C# SWMM6 engine (cs/gen) into Zig (zig/gen/engine.zig), using Roslyn's semantic
// model. See ZIG.md for the mapping.
//
// The C++ engine is translated once, by tools/cpp2x, into C#, where every template is instantiated, every overload
// and implicit conversion is resolved and every reference is an explicit `ref`. That C# is held byte for byte to
// the C++ reference by gate/gate.py. This program reads it with the compiler's own semantic model and writes the
// same program in Zig: classes become structs held by optional pointers, inheritance an embedded base struct and a
// type id, virtual calls a switch on the type id, exceptions Zig error unions with the thrown object held by the
// runtime, lambdas functions with a context of pointers to the captured variables, and the C# runtime (namespace
// Cpp) the Zig runtime in zig/rt. The Zig engine is then gated against the C++ reference in its own right.
//
//   dotnet bin/cs2zig.dll CS_DIR ZIG_GEN_DIR
//
// Written by Claude (Anthropic) for the SWMM6 ports; see AI-USE.md.
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

public sealed class Todo : Exception { public Todo(string m) : base(m) { } }

public static partial class Cs2Zig
{
    static CSharpCompilation comp = null!;
    static readonly Dictionary<SyntaxTree, SemanticModel> models = new();
    static SemanticModel M(SyntaxNode n) => models[n.SyntaxTree];
    static readonly SortedDictionary<string, int> todos = new();
    static readonly SortedDictionary<string, string> manifest = new();   // runtime member used -> its Zig name
    // everything after the type declarations: functions, lambdas, thunks, dispatchers
    static readonly StringBuilder funcs = new();
    static readonly StringBuilder statics = new();
    static readonly List<string> staticInit = new();

    public static int Main(string[] args)
    {
        var cs = args[0];
        var outDir = args[1];
        var files = Directory.GetFiles(Path.Combine(cs, "gen"), "*.cs").Concat(Directory.GetFiles(Path.Combine(cs, "runtime"), "*.cs"))
            .Where(f => !f.EndsWith("Program.cs")).OrderBy(f => f, StringComparer.Ordinal).ToArray();
        var opts = new CSharpParseOptions(LanguageVersion.Latest);
        var trees = files.Select(f => CSharpSyntaxTree.ParseText(File.ReadAllText(f), opts, f)).ToList();
        var fw = Path.GetDirectoryName(typeof(object).Assembly.Location)!;
        var refs = new List<MetadataReference>();
        foreach (var f in Directory.GetFiles(fw, "*.dll"))
        {
            var b = Path.GetFileName(f);
            if (b.StartsWith("Microsoft.VisualBasic") || b == "mscorlib.dll") continue;
            try { refs.Add(MetadataReference.CreateFromFile(f)); } catch { }
        }
        comp = CSharpCompilation.Create("engine", trees, refs, new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, allowUnsafe: true));
        var errs = comp.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToList();
        if (errs.Count > 0) { foreach (var e in errs.Take(10)) Console.Error.WriteLine(e); return 1; }
        foreach (var t in trees) models[t] = comp.GetSemanticModel(t);
        // the engine: the generated C#, and the hand-written engine parts kept with the runtime (Hand_*.cs)
        var gen = trees.Where(t => t.FilePath.Contains("/gen/") || Path.GetFileName(t.FilePath).StartsWith("Hand_")).ToList();

        Directory.CreateDirectory(outDir);
        CollectTypes(gen);
        var types = new StringBuilder();
        var declared = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        foreach (var t in gen)
        {
            foreach (var td in t.GetRoot().DescendantNodes().OfType<BaseTypeDeclarationSyntax>())
                TypeDecl(td, types, declared);
        }
        var sb = new StringBuilder();
        sb.Append("// Code generated by tools/cs2x/Cs2Zig.cs from cs/gen (the C# translation of OpenSWMM 6, swmm6_rel 88329d6). DO NOT EDIT.\n");
        sb.Append("// OpenSWMM 6 is Apache-2.0 (HydroCouple Developers), derived in part from public-domain EPA SWMM; see zig/README.md.\n\n");
        sb.Append("const std = @import(\"std\");\nconst rt = @import(\"../rt/rt.zig\");\nconst E = rt.E;\n\n");
        sb.Append(types);
        sb.Append("// ---------------------------------------------------------------- static fields\n").Append(statics);
        sb.Append("\npub fn __static_init() E!void {\n");
        foreach (var s in staticInit) sb.Append(s);
        sb.Append("}\n\n");
        sb.Append(TypeIdTables());
        sb.Append(funcs);
        File.WriteAllText(Path.Combine(outDir, "engine.zig"), sb.ToString());
        using (var w = new StreamWriter(Path.Combine(outDir, "..", "cs2zig_todo.txt")))
            foreach (var kv in todos.OrderByDescending(kv => kv.Value)) w.WriteLine("{0,6}  {1}", kv.Value, kv.Key);
        using (var w = new StreamWriter(Path.Combine(outDir, "..", "cs2zig_runtime.txt")))
            foreach (var kv in manifest) w.WriteLine(kv.Key + "\t" + kv.Value);
        Console.WriteLine("wrote engine.zig, " + todos.Count + " TODO kinds, " + todos.Values.Sum() + " TODO sites");
        return 0;
    }

    static void Note(string what) { todos[what] = todos.TryGetValue(what, out var c) ? c + 1 : 1; }

    static string Todo(string what)
    {
        todos[what] = todos.TryGetValue(what, out var c) ? c + 1 : 1;
        throw new Todo(what);
    }

    // ------------------------------------------------------------------------------------------------ names
    static readonly HashSet<string> ZigReserved = new()
    {
        "addrspace", "align", "allowzero", "and", "anyframe", "anytype", "asm", "break", "callconv", "catch", "comptime",
        "const", "continue", "defer", "else", "enum", "errdefer", "error", "export", "extern", "fn", "for", "if", "inline",
        "linksection", "noalias", "noinline", "nosuspend", "opaque", "or", "orelse", "packed", "pub", "resume", "return",
        "struct", "suspend", "switch", "test", "threadlocal", "try", "union", "unreachable", "usingnamespace", "var",
        "volatile", "while", "async", "await",
        "bool", "void", "type", "anyerror", "anyopaque", "noreturn", "comptime_int", "comptime_float", "usize", "isize",
        "f16", "f32", "f64", "f80", "f128", "null", "true", "false", "undefined", "std", "rt", "E", "this", "self",
        "c_char", "c_short", "c_ushort", "c_int", "c_uint", "c_long", "c_ulong", "c_longlong", "c_ulonglong", "c_longdouble"
    };

    static string Id(string n)
    {
        n = n.TrimStart('@');
        if (ZigReserved.Contains(n)) return n + "_";
        if (n.Length > 1 && (n[0] == 'i' || n[0] == 'u') && n.Skip(1).All(char.IsDigit)) return "v_" + n;
        return n;
    }

    static bool IsRuntime(ISymbol s)
    {
        var ns = s is INamespaceSymbol nss ? nss : s.ContainingNamespace;
        while (ns != null && !ns.IsGlobalNamespace)
        {
            if (ns.Name == "Cpp" && ns.ContainingNamespace.IsGlobalNamespace) return true;
            ns = ns.ContainingNamespace;
        }
        return false;
    }

    static bool IsSystem(ISymbol s)
    {
        var ns = s.ContainingNamespace;
        while (ns != null && !ns.IsGlobalNamespace) { if (ns.Name == "System" && ns.ContainingNamespace.IsGlobalNamespace) return true; ns = ns.ContainingNamespace; }
        return false;
    }

    static readonly Dictionary<ISymbol, string> typeNames = new(SymbolEqualityComparer.Default);

    /// <summary>The Zig identifier of an engine type: its namespace below openswmm and its class nesting, joined by _.</summary>
    static string TypeIdent(INamedTypeSymbol t)
    {
        t = t.OriginalDefinition;
        if (typeNames.TryGetValue(t, out var n)) return n;
        var parts = new List<string>();
        for (var c = t; c != null; c = c.ContainingType) parts.Insert(0, c.Name);
        var ns = new List<string>();
        for (var x = t.ContainingNamespace; x != null && !x.IsGlobalNamespace; x = x.ContainingNamespace) ns.Insert(0, x.Name);
        if (ns.Count > 0 && (ns[0] == "openswmm" || ns[0] == "_global" || ns[0] == "Gen")) ns.RemoveAt(0);
        var s = "T_" + string.Join("_", ns.Concat(parts));
        typeNames[t] = s;
        return s;
    }

    static string NsPrefix(INamedTypeSymbol t)
    {
        if (t.Name == "_F" && t.ContainingType == null)
        {
            var ns = new List<string>();
            for (var x = t.ContainingNamespace; x != null && !x.IsGlobalNamespace; x = x.ContainingNamespace) ns.Insert(0, x.Name);
            if (ns.Count > 0 && (ns[0] == "openswmm" || ns[0] == "_global")) ns.RemoveAt(0);
            return "F_" + string.Join("_", ns);
        }
        return TypeIdent(t);
    }

    /// <summary>A method's Zig name: the type (or namespace of free functions), two underscores, the method, and a
    /// suffix of its parameter types when the type has several methods of that name.</summary>
    static string FuncName(IMethodSymbol m) => NsPrefix(m.ContainingType.OriginalDefinition) + "__" + MethodIdent(m);

    static string StaticFieldName(IFieldSymbol f) => "G_" + NsPrefix(f.ContainingType.OriginalDefinition) + "__" + f.Name.TrimStart('@');

    static readonly Dictionary<IMethodSymbol, string> methodNames = new(SymbolEqualityComparer.Default);

    static string MethodIdent(IMethodSymbol m)
    {
        m = m.OriginalDefinition;
        if (methodNames.TryGetValue(m, out var n)) return n;
        var t = m.ContainingType;
        var same = t.GetMembers(m.Name).OfType<IMethodSymbol>().Where(x => x.MethodKind == MethodKind.Ordinary).ToList();
        var nm = m.Name.TrimStart('@');
        if (same.Count > 1)
            nm += "__" + string.Join("_", m.Parameters.Select(p => ShortType(p.Type) + (p.RefKind != RefKind.None ? "r" : "")));
        methodNames[m] = nm;
        return nm;
    }

    static string ShortType(ITypeSymbol t)
    {
        switch (t.SpecialType)
        {
            case SpecialType.System_Int32: return "i";
            case SpecialType.System_Int64: return "l";
            case SpecialType.System_UInt64: return "ul";
            case SpecialType.System_UInt32: return "u";
            case SpecialType.System_Double: return "d";
            case SpecialType.System_Single: return "f";
            case SpecialType.System_Boolean: return "b";
            case SpecialType.System_SByte: return "c";
            case SpecialType.System_Byte: return "uc";
            case SpecialType.System_Int16: return "s";
            case SpecialType.System_UInt16: return "us";
            case SpecialType.System_Object: return "o";
            case SpecialType.System_String: return "str";
        }
        if (t is IArrayTypeSymbol at) return ShortType(at.ElementType) + "A";
        if (t is ITypeParameterSymbol tp) return tp.Name;
        if (t is INamedTypeSymbol nt)
        {
            var s = nt.Name;
            if (nt.TypeArguments.Length > 0) s += string.Join("", nt.TypeArguments.Select(ShortType));
            return s;
        }
        return "x";
    }

    static string FieldIdent(IFieldSymbol f) => Id(f.Name);

    static string Cap(string s) => s.Length == 0 ? s : char.ToUpperInvariant(s[0]) + s.Substring(1);
}
