#!/bin/sh
# Write zig/rt/primes.zig, libstdc++'s std::__detail::__prime_list, from the C# runtime's cs/runtime/PrimeList.cs
# (which tests/stdcheck/primes.cpp extracted from the system libstdc++): the lines of numbers with their UL suffixes
# dropped. Written by Claude (Anthropic) for Robert Dickinson's SWMM6 ports; see AI-USE.md and zig/README.md.
set -e
cd "$(dirname "$0")"
{
  echo "//! primes.zig - libstdc++'s __prime_list (from cs/runtime/PrimeList.cs, generated by tests/stdcheck/primes.cpp from the"
  echo "//! system libstdc++), for the hash tables' rehash policy. Written by Claude (Anthropic) for the SWMM6 ports; see AI-USE.md."
  echo "pub const P = [_]u64{"
  grep -E '^[0-9]' ../cs/runtime/PrimeList.cs | sed -E 's/UL//g'
  echo "};"
} > "${1:-rt/primes.zig}"
